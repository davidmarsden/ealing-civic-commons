#!/usr/bin/env node
// Dark-mode palette for hard-coded colours in the site's stylesheets.
//
// The site's colours are partly tokens (--ink, --paper, …, redefined for dark mode
// in appearance.css) and partly literals written into page stylesheets. This
// wraps each literal that would be wrong on a dark page in a custom property
// with the literal as its fallback, e.g. `background: #f3e4d8` becomes
// `background: var(--dark-bg-f3e4d8, #f3e4d8)`. Light mode never defines these
// properties, so it renders exactly as before; appearance.css defines them for
// dark mode with a generated counterpart of the same hue:
//   - backgrounds and borders that are light become dark surfaces and lines;
//   - text that is dark becomes light (white text is left, as it sits on fills);
//   - translucent tints keep their alpha and get a light counterpart;
//   - accent tokens used as fills (--green, --amber, …) keep their light-mode
//     colours via --fill-*, since dark mode redefines those tokens for text.
//
//   node scripts/dark-palette.mjs          rewrite stylesheets and the palette block
//   node scripts/dark-palette.mjs --check  fail if anything is unwrapped or missing
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const PUBLIC = 'public';
const APPEARANCE = join(PUBLIC, 'appearance.css');
const BEGIN = '/* dark-palette:begin (generated by scripts/dark-palette.mjs) */';
const END = '/* dark-palette:end */';
const LITERAL = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\b(?:white|black)\b/g;
const FILL_TOKENS = ['green', 'green-dark', 'amber', 'blue', 'purple'];
const CARD_DARK = { r: 39, g: 55, b: 51 }; // --card in dark mode
const NEUTRAL_DARK = { h: 165, s: .17 }; // hue and saturation of the dark --paper and --card
const chroma = ({ r, g, b }) => (Math.max(r, g, b) - Math.min(r, g, b)) / 255;
export const FILL_DARK = { green: '#2e7353', 'green-dark': '#24513d', amber: '#b25a26', blue: '#315a78', purple: '#6b4a6e' };

const roleOf = prop => {
  if (/^(color|-webkit-text-fill-color|caret-color|text-decoration-color)$/.test(prop)) return 'fg';
  if (/^background(-color|-image)?$/.test(prop) || prop === 'fill') return 'bg';
  if (/^(border|outline)(-[a-z]+)*$/.test(prop) || prop === 'stroke' || prop === 'column-rule') return 'line';
  return null;
};

// Colour parsing and conversion (sRGB, HSL).
export function parseColor(text) {
  const value = text.trim().toLowerCase();
  if (value === 'white') return { r: 255, g: 255, b: 255, a: 1 };
  if (value === 'black') return { r: 0, g: 0, b: 0, a: 1 };
  if (value.startsWith('#')) {
    let hex = value.slice(1);
    if (hex.length === 3 || hex.length === 4) hex = [...hex].map(c => c + c).join('');
    if (hex.length !== 6 && hex.length !== 8) return null;
    const n = i => parseInt(hex.slice(i, i + 2), 16);
    return { r: n(0), g: n(2), b: n(4), a: hex.length === 8 ? n(6) / 255 : 1 };
  }
  const m = value.match(/^rgba?\(([^)]*)\)$/);
  if (!m) return null;
  const parts = m[1].split(/[\s,/]+/).filter(Boolean).map(Number);
  if (parts.length < 3 || parts.some(Number.isNaN)) return null;
  return { r: parts[0], g: parts[1], b: parts[2], a: parts[3] ?? 1 };
}
const toHsl = ({ r, g, b }) => {
  [r, g, b] = [r / 255, g / 255, b / 255];
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return { h: 0, s: 0, l };
  const d = max - min, s = l > .5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return { h: h * 60, s, l };
};
const fromHsl = ({ h, s, l }) => {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1))));
  return { r: f(0), g: f(8), b: f(4) };
};
const hex = ({ r, g, b }) => `#${[r, g, b].map(v => v.toString(16).padStart(2, '0')).join('')}`;
const format = (rgb, a) => a >= 1 ? hex(rgb) : `rgba(${rgb.r},${rgb.g},${rgb.b},${+a.toFixed(3)})`;
const clamp = v => Math.max(0, Math.min(1, v));

// The dark-mode counterpart of a literal in a role, or null when the literal
// already works on a dark page (dark fills, white text, shadows).
export function darkCounterpart(role, color) {
  const { h, s, l } = toHsl(color);
  const translucent = color.a < .5;
  if (translucent) {
    // Light veils (white at low alpha) would grey a dark page: keep a trace.
    if (l >= .6) return role === 'bg' ? format(color, color.a * .2) : null;
    // Tints and hairlines: dark ink at low alpha becomes light ink at the same alpha.
    return format(fromHsl({ h, s: s * .6, l: clamp(.92 - l * .2) }), color.a);
  }
  if (role === 'bg') {
    if (l < .6) return null;
    // White and near-white panels are cards: use the dark card colour.
    if (l >= .96) return format(CARD_DARK, color.a);
    // Cream and paper tones are the light theme's neutrals: give them the dark
    // theme's neutral hue rather than turning them brown. Real tints keep theirs.
    const neutral = chroma(color) < .08 && h >= 34 && h <= 70;
    return format(fromHsl(neutral ? { ...NEUTRAL_DARK, l: clamp(.18 + (1 - l) * .4) } : { h, s: s * .45, l: clamp(.18 + (1 - l) * .4) }), color.a);
  }
  if (role === 'line') {
    if (l >= .6) return format(fromHsl({ h, s: s * .4, l: clamp(.3 + (1 - l) * .35) }), color.a);
    return format(fromHsl({ h, s: s * .7, l: clamp(.82 - l * .3) }), color.a);
  }
  // Text.
  if (l >= .8) return null;
  return format(fromHsl({ h, s: Math.min(s, .55), l: clamp(Math.max(.72, .95 - l * .5)) }), color.a);
}

const tokenName = (role, literal) => `--dark-${role}-${literal.toLowerCase().replace(/^#/, '').replace(/[^0-9a-z.]+/g, '-').replace(/\./g, '_').replace(/^-|-$/g, '')}`;

// Rewrites one stylesheet's declarations. Returns { css, tokens, unwrapped }.
export function transformCss(css) {
  const tokens = new Map();
  const unwrapped = [];
  const comments = [];
  const masked = css.replace(/\/\*[\s\S]*?\*\//g, match => { comments.push(match); return `\u0000${comments.length - 1}\u0000`; });
  const out = masked.replace(/([^{}]*)\{([^{}]*)\}/g, (rule, selector, body) => {
    if (/(^|[\s,]):root\b/.test(selector.replace(/\u0000\d+\u0000/g, ''))) return rule;
    const next = body.replace(/(^|;|\s)([a-z-]+)(\s*:\s*)([^;]+)/g, (decl, lead, prop, colon, value) => {
      const role = roleOf(prop);
      if (!role || prop.startsWith('--')) return decl;
      let changed = value;
      if (role === 'bg') {
        changed = changed.replace(/var\(--(green-dark|green|amber|blue|purple)\)/g, (match, name, offset, whole) =>
          /var\(--fill-[\w-]+,\s*$/.test(whole.slice(0, offset)) ? match : `var(--fill-${name}, var(--${name}))`);
      }
      changed = changed.replace(LITERAL, (literal, ...rest) => {
        const whole = rest.at(-1), offset = rest.at(-2);
        if (/var\(--[\w-]+,\s*$/.test(whole.slice(0, offset))) return literal;
        const color = parseColor(literal);
        if (!color) return literal;
        const dark = darkCounterpart(role, color);
        if (!dark) return literal;
        const name = tokenName(role, literal);
        tokens.set(name, dark);
        return `var(${name}, ${literal})`;
      });
      // Already-wrapped literals still need their tokens defined.
      for (const m of changed.matchAll(/var\((--dark-(fg|bg|line)-[\w-]+),\s*([^)]*\)?)\)/g)) {
        const color = parseColor(m[3].replace(/\)\)$/, ')'));
        const dark = color && darkCounterpart(m[2], color);
        if (dark) tokens.set(m[1], dark); else unwrapped.push(m[1]);
      }
      return `${lead}${prop}${colon}${changed}`;
    });
    return `${selector}{${next}}`;
  });
  return { css: out.replace(/\u0000(\d+)\u0000/g, (_, i) => comments[+i]), tokens, unwrapped };
}

async function sources() {
  const files = [
    ...(await readdir(PUBLIC)).filter(name => name.endsWith('.css') && name !== 'appearance.css').map(name => join(PUBLIC, name)),
    ...(await readdir(join(PUBLIC, 'brand'))).filter(name => name.endsWith('.css')).map(name => join(PUBLIC, 'brand', name))
  ];
  const pages = (await readdir(PUBLIC)).filter(name => name.endsWith('.html')).map(name => join(PUBLIC, name));
  return { files, pages };
}

export async function run({ check = false } = {}) {
  const { files, pages } = await sources();
  const tokens = new Map();
  const changedFiles = [];
  const apply = async (file, transform) => {
    const before = await readFile(file, 'utf8');
    const after = transform(before);
    if (after !== before) { changedFiles.push(file); if (!check) await writeFile(file, after); }
  };
  const collect = css => { const result = transformCss(css); for (const [k, v] of result.tokens) tokens.set(k, v); return result.css; };
  for (const file of files) await apply(file, collect);
  for (const page of pages) await apply(page, html => html.replace(/(<style[^>]*>)([\s\S]*?)(<\/style>)/gi, (m, open, css, close) => open + collect(css) + close));

  const block = [BEGIN, ':root[data-theme="dark"] {', ...FILL_TOKENS.map(name => ` --fill-${name}:${FILL_DARK[name]};`), ...[...tokens].sort().map(([k, v]) => ` ${k}:${v};`), '}', END].join('\n');
  const appearance = await readFile(APPEARANCE, 'utf8');
  const start = appearance.indexOf(BEGIN), stop = appearance.indexOf(END);
  const nextAppearance = start >= 0 && stop > start
    ? appearance.slice(0, start) + block + appearance.slice(stop + END.length)
    : `${appearance.trimEnd()}\n${block}\n`;
  if (nextAppearance !== appearance) { changedFiles.push(APPEARANCE); if (!check) await writeFile(APPEARANCE, nextAppearance); }
  return { changedFiles, tokens: tokens.size };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  const { changedFiles, tokens } = await run({ check });
  if (check && changedFiles.length) {
    console.error(`Dark palette is out of date in: ${changedFiles.join(', ')}\nRun: node scripts/dark-palette.mjs`);
    process.exit(1);
  }
  console.log(check ? `Dark palette up to date (${tokens} tokens).` : `Dark palette: ${tokens} tokens; updated ${changedFiles.length} files.`);
}
